'use strict';
/**
 * Writes docs/SECURITY-MEASURES.md from src/config/securityPosture.js — the
 * same source as the About page, so the two never disagree.
 *   node scripts/export-security-measures.js          (write)
 *   node scripts/export-security-measures.js --check  (exit 1 if out of date)
 */
const fs = require('fs');
const path = require('path');
const { CATEGORIES, totals } = require('../src/config/securityPosture');

const OUT = path.join(__dirname, '..', 'docs', 'SECURITY-MEASURES.md');

function render() {
    const t = totals();
    const L = [];
    L.push('# Security measures');
    L.push('');
    L.push(
        '<!-- Generated by scripts/export-security-measures.js from src/config/securityPosture.js. Do not edit by hand. -->'
    );
    L.push('');
    L.push(
        `IDevelop Community Edition documents **${t.controls} security controls** in ${t.categories} areas. Each one cites the code that implements it and the automated tests that prove it. The same list is shown in the application under **About → Security**.`
    );
    L.push('');
    L.push(
        'A test (`tests/unit/securityPostureEvidence.test.js`) fails if a cited file or test disappears, so this page cannot claim a control the code no longer has.'
    );
    L.push('');
    for (const c of CATEGORIES) {
        L.push(`## ${c.title.en}`);
        L.push('');
        L.push('| Control | Implemented in | Proven by |');
        L.push('| ------- | -------------- | --------- |');
        for (const x of c.controls) {
            const ev = x.evidence.map((e) => '`' + e + '`').join('<br>');
            const ts = x.tests.length
                ? x.tests.map((e) => '`tests/unit/' + e + '`').join('<br>')
                : 'CI pipeline';
            L.push(`| ${x.en} | ${ev} | ${ts} |`);
        }
        L.push('');
    }
    L.push('## Running the security tests');
    L.push('');
    L.push('```bash');
    L.push('npm test                                   # the whole suite, as CI runs it');
    L.push(
        'npx jest tests/unit/webSecurityBaseline.test.js tests/unit/securityControls.test.js tests/unit/securityPostureEvidence.test.js'
    );
    L.push('npm audit --omit=dev                       # known vulnerabilities in dependencies');
    L.push('```');
    L.push('');
    L.push('## Known limitations');
    L.push('');
    L.push(
        "- The CSP still allows inline event handlers (`script-src-attr 'unsafe-inline'`) and inline styles; inline `<script>` blocks need the per-request nonce. Moving the remaining `onclick=` handlers to scripts is planned."
    );
    L.push(
        '- Without `APP_KEY` or `SESSION_SECRET` (development only), stored secrets are kept in clear; production refuses to start without a strong secret.'
    );
    L.push(
        '- No independent penetration test has been published yet. One is recommended before general availability; see `docs/SECURITY-AUDIT.md` for the internal audit and `SECURITY.md` for reporting a vulnerability.'
    );
    L.push('');
    return L.join('\n');
}

/** Rendered and formatted like the repository's Prettier config. */
async function formatted() {
    // eslint-disable-next-line n/no-unpublished-require -- documentation tooling, dev only
    const prettier = require('prettier');
    const opts = (await prettier.resolveConfig(OUT)) || {};
    return prettier.format(render(), { ...opts, parser: 'markdown' });
}

async function main() {
    const out = await formatted();
    if (process.argv.includes('--check')) {
        const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
        if (cur.trim() !== out.trim()) {
            console.error('docs/SECURITY-MEASURES.md is out of date: run npm run security:doc');
            process.exit(1);
        }
        console.log('docs/SECURITY-MEASURES.md is up to date');
    } else {
        fs.writeFileSync(OUT, out);
        console.log('wrote', path.relative(process.cwd(), OUT));
    }
}

if (require.main === module) main();

module.exports = { render, formatted };
